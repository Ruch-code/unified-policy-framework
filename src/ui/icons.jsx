// Icon layer for the site. Decorative icons render nothing; icons that do a job render a plain text mark.
// Wired in through a Vite alias for 'lucide-react', so components keep their existing imports.
// tests/icons.test.mjs fails if a component imports an icon that is not listed here.
import React from 'react';

const sizeless = (c = '') => String(c).split(/\s+/).filter((t) => t && !/^(w|h|size|min-w|min-h)-/.test(t)).join(' ');
const glyph = (g) => function Glyph({ className = '' }) {
  return <span aria-hidden="true" className={`inline-flex items-center justify-center leading-none select-none ${className}`}>{g}</span>;
};
const label = (t) => function Label({ className = '' }) {
  return <span aria-hidden="true" className={`text-xs font-semibold leading-none ${sizeless(className)}`}>{t}</span>;
};
const box = (filled) => function Box({ className = '' }) {
  return <span aria-hidden="true" className={`inline-block shrink-0 border-2 border-current ${filled ? 'bg-current' : ''} ${sizeless(className)}`} style={{ width: '0.85em', height: '0.85em', borderRadius: 2 }} />;
};
function Spinner({ className = '' }) {
  return <span role="status" aria-label="Loading" className={`inline-block rounded-full border-2 border-current border-t-transparent animate-spin ${className}`} />;
}
const none = function NoIcon() { return null; };

